  function resizeCanvas() {
    const rect = canvas.getBoundingClientRect();
    dpr = Math.min(window.devicePixelRatio || 1, 2);
    width = rect.width;
    height = rect.height;
    canvas.width = Math.round(width * dpr);
    canvas.height = Math.round(height * dpr);
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    const area = width * height;
    const count = width < 640
      ? Math.round(Math.min(26, Math.max(16, area / 22000)))
      : Math.round(Math.min(90, Math.max(28, area / 16000)));
    nodes = Array.from({ length: count }, () => ({
      x: Math.random() * width,
      y: Math.random() * height,
      vx: (Math.random() - 0.5) * 0.35,
      vy: (Math.random() - 0.5) * 0.35,
      r: Math.random() * 1.6 + 0.8
    }));
  }

  function hexToRgb(hex) {
    const h = hex.replace("#", "");
    const n = parseInt(h.length === 3 ? h.split("").map((c) => c + c).join("") : h, 16);
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
  }

  function draw() {
    const [r, g, b] = getAccentRgb();
    const maxDist = 140;
    ctx.clearRect(0, 0, width, height);

    for (const node of nodes) {
      if (!reduceMotion) {
        // Atracción suave hacia el puntero.
        const dx = pointer.x - node.x;
        const dy = pointer.y - node.y;
        const dist = Math.hypot(dx, dy);
        if (dist < 180 && dist > 1) {
          node.vx += (dx / dist) * 0.012;
          node.vy += (dy / dist) * 0.012;
        }
        node.vx *= 0.99;
        node.vy *= 0.99;
        const speed = Math.hypot(node.vx, node.vy);
        if (speed < 0.12) { node.vx += (Math.random() - 0.5) * 0.05; node.vy += (Math.random() - 0.5) * 0.05; }
        node.x += node.vx;
        node.y += node.vy;
        if (node.x < 0 || node.x > width) node.vx *= -1;
        if (node.y < 0 || node.y > height) node.vy *= -1;
        node.x = Math.max(0, Math.min(width, node.x));
        node.y = Math.max(0, Math.min(height, node.y));
      }
    }

    for (let i = 0; i < nodes.length; i++) {
      for (let j = i + 1; j < nodes.length; j++) {
        const a = nodes[i];
        const c = nodes[j];
        const d = Math.hypot(a.x - c.x, a.y - c.y);
        if (d < maxDist) {
          ctx.strokeStyle = `rgba(${r}, ${g}, ${b}, ${(1 - d / maxDist) * 0.22})`;
          ctx.lineWidth = 1;
          ctx.beginPath();
          ctx.moveTo(a.x, a.y);
          ctx.lineTo(c.x, c.y);
          ctx.stroke();
        }
      }
    }

    for (const node of nodes) {
      const near = Math.hypot(pointer.x - node.x, pointer.y - node.y) < 120;
      ctx.fillStyle = `rgba(${r}, ${g}, ${b}, ${near ? 0.95 : 0.55})`;
      ctx.beginPath();
      ctx.arc(node.x, node.y, near ? node.r + 1 : node.r, 0, Math.PI * 2);
      ctx.fill();
    }
  }

